def parse_md_tables(path):
    tables, header, rows = [], None, []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("|") and s.endswith("|"):
            cells = [c.strip() for c in s.strip("|").split("|")]
            if all(re.fullmatch(r":?-{3,}:?", c) for c in cells if c):
                continue
            if header is None:
                header = cells
            else:
                rows.append(cells + [""] * (len(header) - len(cells)))
        else:
            if header is not None:
                tables.append((header, rows))
                header, rows = None, []
    if header is not None:
        tables.append((header, rows))
    return tables


def find_table(path, must_all, min_rows=1, occurrence=0):
    matches = []
    for header, rows in parse_md_tables(path):
        joined = "|".join(header)
        if all(k in joined for k in must_all) and len(rows) >= min_rows:
            matches.append((header, rows))
    if occurrence >= len(matches):
        raise KeyError("table not found: %s occ=%d in %s" % (must_all, occurrence, Path(path).name))
    return matches[occurrence]


def _norm(table):
    """统一块格式：接受 (header, rows) 元组或 [header, row, row...] 扁平表。"""
    header = table[0]
    rest = list(table[1:])
    if len(rest) == 1 and isinstance(rest[0], list) and (not rest[0] or isinstance(rest[0][0], (list, tuple))):
        rows = [list(r) for r in rest[0]]
    else:
        rows = [list(r) if isinstance(r, (list, tuple)) else [str(r)] for r in rest]
    return header, rows


def write_sheet(wb, title, blocks, widths=None):
    ws = wb.create_sheet(title)
    for text, table in blocks:
        header, data = _norm(table)
        r = ws.max_row + 2 if ws["A1"].value else 1
        ws.cell(row=r, column=1, value=text).font = SECTION_FONT
        r += 1
        for i, h in enumerate(header, start=1):
            c = ws.cell(row=r, column=i, value=h)
            c.font = HEADER_FONT
            c.fill = HEADER_FILL
            c.border = BORDER
        for row in data:
            r += 1
            for i, v in enumerate(row, start=1):
                c = ws.cell(row=r, column=i, value=v)
                c.border = BORDER
                c.alignment = Alignment(vertical="top", wrap_text=True)
    if widths is None:
        all_rows, ncols = [], 1
        for _t, tbl in blocks:
            h, d = _norm(tbl)
            ncols = max(ncols, len(h))
            all_rows.append(h)
            all_rows.extend(d)
        widths = []
        for i in range(ncols):
            longest = max((len(str(r[i])) for r in all_rows if i < len(r) and r[i] is not None), default=0)
            widths.append(min(58, max(10, longest * 1.7 + 2)))
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    return ws


def _clean_cell(v):
    return str(v).replace("**", "").replace("`", "") if isinstance(v, str) else v

def T(path, keys, min_rows=1, occurrence=0, drop_cols=()):
    header, rows = find_table(ECON / path, keys, min_rows=min_rows, occurrence=occurrence)
    header = [_clean_cell(h) for h in header]
    rows = [[_clean_cell(c) for c in r] for r in rows]
    if drop_cols:
        keep = [i for i, h in enumerate(header) if not any(k in h for k in drop_cols)]
        header = [header[i] for i in keep]
        rows = [[r[i] if i < len(r) else "" for i in keep] for r in rows]
    return header, rows



import fs from "node:fs";
import path from "node:path";
import cp from "node:child_process";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..", "..");
const stageRoot = path.resolve(process.argv[2]);
const kb = path.join(repoRoot, "knowledge-base");
const read = p => JSON.parse(fs.readFileSync(p, "utf8"));
const gates = [];
const gate = (name, pass, detail = "") => gates.push({ name, pass: Boolean(pass), detail });
const skills = read(path.join(kb, "registries", "skill-registry.json"));
const model = read(path.join(kb, "registries", "knowledge-model.json"));
const nodes = read(path.join(kb, "registries", "framework-nodes.json"));
const systemSkill = read(path.join(kb, "mappings", "system-to-skill.json"));
const qSkill = read(path.join(kb, "mappings", "question-to-skill.json"));
const sLayer = read(path.join(kb, "mappings", "skill-to-knowledge-layer.json"));
const sEvidence = read(path.join(kb, "mappings", "skill-to-evidence.json"));
const authority = read(path.join(kb, "AUTHORITY.json"));
const rulings = read(path.join(kb, "governance", "rulings.json"));
const graph = read(path.join(stageRoot, "understand", "knowledge-graph.json"));
const skillFiles = cp.execFileSync("rg", ["--files", path.join(repoRoot, "skills"), "-g", "SKILL.md"], { encoding: "utf8" }).trim().split(/\r?\n/).filter(Boolean);
const skillIds = new Set(skills.skills.map(x => x.skillId));
const systemIds = new Set(model.systems.map(x => x.id));
gate("skill-files-33", skillFiles.length === 33, `${skillFiles.length}/33`);
gate("skill-registry-33", skills.skills.length === 33 && skillIds.size === 33, `${skills.skills.length}/33`);
gate("skill-fields-complete", skills.skills.every(x => ["skillId","category","responsibility","triggers","inputs","outputs","coveredSystems","dependsOnSkills","evidenceSources","deliveryGates","versionStatus"].every(k => x[k] && (!Array.isArray(x[k]) || x[k].length > 0 || k === "dependsOnSkills"))));
gate("skill-source-exists", skills.skills.every(x => fs.existsSync(path.join(repoRoot, x.sourcePath))));
gate("skill-routes-33", qSkill.rules.length === 33 && qSkill.rules.every(x => skillIds.has(x.primarySkill)), `${qSkill.rules.length}/33`);
gate("system-skill-coverage", systemSkill.mappings.length === model.systems.length && systemSkill.mappings.every(x => x.skills.length > 0 && systemIds.has(x.systemId)), `${systemSkill.mappings.length}/${model.systems.length}`);
gate("system-skill-valid", systemSkill.mappings.every(x => x.skills.every(s => skillIds.has(s))));
gate("skill-layer-33", sLayer.mappings.length === 33 && sLayer.mappings.every(x => x.frameworkNodeIds.length > 0));
gate("skill-evidence-33", sEvidence.mappings.length === 33 && sEvidence.mappings.every(x => x.evidenceSources.length > 0));
gate("framework-nodes-19", nodes.nodes.length === 19 && new Set(nodes.nodes.map(x => x.id)).size === 19, `${nodes.nodes.length}/19`);
gate("single-authority-entry", authority.formalEntry === "knowledge-base/README.md" && nodes.formalEntry === authority.formalEntry);
gate("canonical-tracked", cp.spawnSync("git", ["-C", repoRoot, "check-ignore", "knowledge-base/README.md"]).status !== 0);
gate("output-is-generated", fs.existsSync(path.join(stageRoot, "build-manifest.json")) && fs.existsSync(path.join(stageRoot, "knowledge-base", "router-manifest.json")));
gate("ruling-rv-c", rulings.rulings.some(x => x.rulingId === "RULING-RV-C" && x.decision.includes("+30/+60/+100") && x.decision.includes("50/30/20")));
gate("ruling-ew-b", rulings.rulings.some(x => x.rulingId === "RULING-EW-B" && x.decision.includes("一个大版本")));
const authorityText = [path.join(kb, "framework"), path.join(kb, "system-details"), path.join(kb, "domains"), path.join(repoRoot, "skills")]
  .flatMap(root => {
    const out = cp.execFileSync("rg", ["--files", root], { encoding: "utf8" }).trim();
    return out ? out.split(/\r?\n/) : [];
  }).filter(p => /\.(md|json|py)$/.test(p)).map(p => fs.readFileSync(p, "utf8")).join("\n");
gate("no-active-ew-unresolved", !/C-001 未裁决|专武迁移未裁决|迁移冲突未裁决|迁移方向未裁决/.test(authorityText));
gate("no-active-old-ew-ruling", !/专武线废弃并迁移到收容物|专武立即清理|长期双轨/.test(authorityText));
gate("no-active-old-rv-ruling", !/固定\+?100|不参与随机强化|不参与随机结果/.test(authorityText));
const rv = read(path.join(kb, "system-details", "SYS-OUT-GR-09.json"));
const rvRule = rv.rules.find(x => x.id === "SYS-OUT-GR-09-R02");
gate("rv-rule-current", rvRule.targetRule.includes("+30/+60/+100") && rvRule.targetRule.includes("50/30/20"));
const ew = read(path.join(kb, "system-details", "SYS-OUT-GR-10.json"));
gate("ew-rule-current", ew.rules.find(x => x.id === "SYS-OUT-GR-10-R03").targetRule.includes("一个大版本"));
const archive = read(path.join(repoRoot, "archive", "legacy-output-20260824", "manifest.json"));
gate("legacy-archive-traceable", archive.fileCount > 0 && archive.files.every(x => x.sha256 && x.disposition), String(archive.fileCount));
gate("no-authority-output-dependency", !authorityText.includes("D:\\Vgame_design\\output\\项目级策划知识框架"));
const nodeIds = new Set(graph.nodes.map(x => x.id));
gate("understand-graph-nodes", graph.nodes.length >= 97 && nodeIds.size === graph.nodes.length, String(graph.nodes.length));
gate("understand-graph-edges", graph.edges.length > 0 && graph.edges.every(x => nodeIds.has(x.source) && nodeIds.has(x.target)), String(graph.edges.length));
gate("understand-layers-valid", graph.layers.every(x => x.nodeIds.every(id => nodeIds.has(id))));
gate("understand-tour-valid", graph.tour.every(x => x.nodeIds.every(id => nodeIds.has(id))));
const report = { schema: "vgame-v1-gates/v1", generatedAt: new Date().toISOString(), passed: gates.every(x => x.pass), summary: { passed: gates.filter(x => x.pass).length, total: gates.length }, gates };
fs.mkdirSync(path.join(stageRoot, "reports"), { recursive: true });
fs.writeFileSync(path.join(stageRoot, "reports", "v1-gates.json"), `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify(report.summary));
if (!report.passed) {
  for (const x of gates.filter(x => !x.pass)) console.error(`[FAIL] ${x.name}: ${x.detail}`);
  process.exitCode = 1;
}
